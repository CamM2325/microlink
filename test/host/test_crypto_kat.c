static void box_msg(uint8_t *m, size_t len)
{
    for (size_t i = 0; i < len; i++)
        m[i] = (uint8_t)(i * 7 + 3);
}

static void test_nacl_box(void)
{
    static const struct { size_t len; const uint8_t *ct; } V[] = {
        { 0, BOX_CT0 }, { 131, BOX_CT131 }, { 200, BOX_CT200 },
    };
    uint8_t k[32], k2[32], m[256], c[256 + 16], p[256];

    CHECK(nacl_box_beforenm(k, BOB_PK, ALICE_SK) == 0 && memcmp(k, BOX_FIRSTKEY, 32) == 0,
          "nacl: beforenm(bobpk, alicesk) != NaCl firstkey");
    CHECK(nacl_box_beforenm(k2, ALICE_PK, BOB_SK) == 0 && memcmp(k2, BOX_FIRSTKEY, 32) == 0,
          "nacl: beforenm(alicepk, bobsk) != NaCl firstkey");
    CHECK(nacl_box_shared_get(k2, BOB_PK, ALICE_SK) == 0 && memcmp(k2, BOX_FIRSTKEY, 32) == 0,
          "nacl: shared_get (miss) != firstkey");
    CHECK(nacl_box_shared_get(k2, BOB_PK, ALICE_SK) == 0 && memcmp(k2, BOX_FIRSTKEY, 32) == 0,
          "nacl: shared_get (hit) != firstkey");

    for (size_t i = 0; i < sizeof(V) / sizeof(V[0]); i++) {
        size_t len = V[i].len;
        box_msg(m, len);

        memset(c, 0, sizeof(c));
        CHECK(nacl_box(c, m, len, BOX_NONCE, BOB_PK, ALICE_SK) == 0 &&
              memcmp(c, V[i].ct, len + 16) == 0, "nacl: box len %zu", len);
        memset(c, 0, sizeof(c));
        CHECK(nacl_box_afternm(c, m, len, BOX_NONCE, k) == 0 &&
              memcmp(c, V[i].ct, len + 16) == 0, "nacl: box_afternm len %zu", len);

        memset(p, 0xAA, sizeof(p));
        CHECK(nacl_box_open(p, V[i].ct, len + 16, BOX_NONCE, ALICE_PK, BOB_SK) == 0 &&
              memcmp(p, m, len) == 0, "nacl: box_open len %zu", len);
        memset(p, 0xAA, sizeof(p));
        CHECK(nacl_box_open_afternm(p, V[i].ct, len + 16, BOX_NONCE, k) == 0 &&
              memcmp(p, m, len) == 0, "nacl: box_open_afternm len %zu", len);

        for (size_t j = 0; j < len + 16; j += (len + 16) / 7 + 1) {
            memcpy(c, V[i].ct, len + 16);
            c[j] ^= 0x04;
            CHECK(nacl_box_open_afternm(p, c, len + 16, BOX_NONCE, k) != 0,
                  "nacl: len %zu flipped byte %zu accepted", len, j);
        }
    }
    CHECK(nacl_box_open_afternm(p, BOX_CT0, 15, BOX_NONCE, k) != 0, "nacl: short box accepted");
}

