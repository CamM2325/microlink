static void test_x25519(void)
{
    uint8_t out[32], u[32];

    CHECK(x25519(out, X_SCALAR1, X_U1, 1) == 0 && memcmp(out, X_OUT1, 32) == 0,
          "x25519: RFC 7748 5.2 vector 1");

    /* RFC 7748 says to ignore the top bit of u; this implementation does not
     * (see x25519.h), so the caller masks it, as WireGuard keys never set it. */
    memcpy(u, X_U2, 32);
    u[31] &= 0x7f;
    CHECK(x25519(out, X_SCALAR2, u, 1) == 0 && memcmp(out, X_OUT2, 32) == 0,
          "x25519: RFC 7748 5.2 vector 2");

    /* 5.2 iterated: k = X25519(k, u), u = old k, starting from k = u = 9 */
    uint8_t k[32] = { 9 }, uu[32] = { 9 }, r[32];
    for (int i = 1; i <= 1000; i++) {
        x25519(r, k, uu, 1);
        memcpy(uu, k, 32);
        memcpy(k, r, 32);
        if (i == 1)
            CHECK(memcmp(k, X_ITER1, 32) == 0, "x25519: RFC 7748 iterated x1");
    }
    CHECK(memcmp(k, X_ITER1000, 32) == 0, "x25519: RFC 7748 iterated x1000");

    /* 6.1 Diffie-Hellman */
    CHECK(x25519_base(out, ALICE_SK, 1) == 0 && memcmp(out, ALICE_PK, 32) == 0,
          "x25519: RFC 7748 6.1 Alice public key");
    CHECK(x25519_base(out, BOB_SK, 1) == 0 && memcmp(out, BOB_PK, 32) == 0,
          "x25519: RFC 7748 6.1 Bob public key");
    CHECK(x25519(out, ALICE_SK, BOB_PK, 1) == 0 && memcmp(out, DH_SHARED, 32) == 0,
          "x25519: RFC 7748 6.1 shared secret (Alice)");
    CHECK(x25519(out, BOB_SK, ALICE_PK, 1) == 0 && memcmp(out, DH_SHARED, 32) == 0,
          "x25519: RFC 7748 6.1 shared secret (Bob)");

    /* Non-contributory (all-zero) output must be reported */
    uint8_t zero[32] = { 0 };
    CHECK(x25519(out, ALICE_SK, zero, 1) != 0, "x25519: zero point not rejected");
}

