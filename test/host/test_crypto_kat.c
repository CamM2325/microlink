static void test_poly1305(void)
{
    static const char msg[] = "Cryptographic Forum Research Group";
    poly1305_context ctx;
    uint8_t mac[16];

    poly1305_init(&ctx, P_KEY);
    poly1305_update(&ctx, (const unsigned char *)msg, sizeof(msg) - 1);
    poly1305_finish(&ctx, mac);
    CHECK(memcmp(mac, P_TAG, 16) == 0, "poly1305: RFC 8439 2.5.2 (one update)");

    /* Same message fed in uneven pieces exercises the partial-block buffer */
    poly1305_init(&ctx, P_KEY);
    poly1305_update(&ctx, (const unsigned char *)msg, 5);
    poly1305_update(&ctx, (const unsigned char *)msg + 5, 17);
    poly1305_update(&ctx, (const unsigned char *)msg + 22, sizeof(msg) - 1 - 22);
    poly1305_finish(&ctx, mac);
    CHECK(memcmp(mac, P_TAG, 16) == 0, "poly1305: RFC 8439 2.5.2 (split updates)");
}

