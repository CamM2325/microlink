static void test_chacha20poly1305(void)
{
    /* wireguard-lwip takes the nonce as 4 zero bytes || 64-bit little-endian
     * counter. RFC 8439 A.5 uses nonce 00000000 01020304 05060708. */
    const uint64_t nonce = 0x0807060504030201ULL;
    uint8_t buf[sizeof(A5_CT)], out[sizeof(A5_PT)];

    chacha20poly1305_encrypt(buf, A5_PT, sizeof(A5_PT), A5_AAD, sizeof(A5_AAD), nonce, A5_KEY);
    CHECK(memcmp(buf, A5_CT, sizeof(A5_CT)) == 0, "chachapoly: RFC 8439 A.5 seal");

    memset(out, 0, sizeof(out));
    CHECK(chacha20poly1305_decrypt(out, A5_CT, sizeof(A5_CT), A5_AAD, sizeof(A5_AAD), nonce, A5_KEY) &&
          memcmp(out, A5_PT, sizeof(A5_PT)) == 0, "chachapoly: RFC 8439 A.5 open");

    memcpy(buf, A5_CT, sizeof(A5_CT));
    buf[sizeof(buf) - 1] ^= 0x01;
    CHECK(!chacha20poly1305_decrypt(out, buf, sizeof(buf), A5_AAD, sizeof(A5_AAD), nonce, A5_KEY),
          "chachapoly: corrupted tag accepted");
    memcpy(buf, A5_CT, sizeof(A5_CT));
    buf[100] ^= 0x80;
    CHECK(!chacha20poly1305_decrypt(out, buf, sizeof(buf), A5_AAD, sizeof(A5_AAD), nonce, A5_KEY),
          "chachapoly: corrupted ciphertext accepted");
    CHECK(!chacha20poly1305_decrypt(out, A5_CT, sizeof(A5_CT), A5_AAD, sizeof(A5_AAD), nonce + 1, A5_KEY),
          "chachapoly: wrong nonce accepted");
}

