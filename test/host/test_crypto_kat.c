/* RFC 7693 appendix E: deterministic input sequence */
static void selftest_seq(uint8_t *out, size_t len, uint32_t seed)
{
    uint32_t t, a = 0xDEAD4BAD * seed, b = 1;
    for (size_t i = 0; i < len; i++) {
        t = a + b;
        a = b;
        b = t;
        out[i] = (t >> 24) & 0xFF;
    }
}

static void test_blake2s(void)
{
    uint8_t md[32];

    CHECK(blake2s(md, 32, NULL, 0, "abc", 3) == 0 && memcmp(md, B2S_ABC, 32) == 0,
          "blake2s: RFC 7693 appendix B (\"abc\")");

    /* RFC 7693 appendix E: hash of keyed and unkeyed hashes over several
     * digest and input lengths */
    static const size_t md_len[4] = { 16, 20, 28, 32 };
    static const size_t in_len[6] = { 0, 3, 64, 65, 255, 1024 };
    uint8_t in[1024], key[32];
    blake2s_ctx ctx;

    CHECK(blake2s_init(&ctx, 32, NULL, 0) == 0, "blake2s: init");
    for (size_t i = 0; i < 4; i++) {
        size_t outlen = md_len[i];
        for (size_t j = 0; j < 6; j++) {
            size_t inlen = in_len[j];
            selftest_seq(in, inlen, (uint32_t)inlen);
            blake2s(md, outlen, NULL, 0, in, inlen);
            blake2s_update(&ctx, md, outlen);
            selftest_seq(key, outlen, (uint32_t)outlen);
            blake2s(md, outlen, key, outlen, in, inlen);
            blake2s_update(&ctx, md, outlen);
        }
    }
    blake2s_final(&ctx, md);
    CHECK(memcmp(md, B2S_SELFTEST, 32) == 0, "blake2s: RFC 7693 appendix E self-test");
}

